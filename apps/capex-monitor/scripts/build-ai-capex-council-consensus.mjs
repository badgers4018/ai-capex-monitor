import { readFile, writeFile, mkdir } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = join(__dirname, "..");
const asOf = "2026-10-13";
const manifest = JSON.parse(await readFile(join(root, "data", "ai_capex_universe_manifest.json"), "utf8"));
const raw = JSON.parse(await readFile(join(root, "data", `ai_capex_council_raw_${asOf}.json`), "utf8"));
const ntap = JSON.parse(await readFile(join(root, "data", `ai_capex_council_ntap_${asOf}.json`), "utf8"));

const stanceOrder = ["capex-winner", "capex-beneficiary", "balanced", "capex-risk"];
const convictionValue = { low: 1, medium: 2, high: 3 };
const convictionLabel = (value) => value >= 2.6 ? "high" : value >= 1.6 ? "medium" : "low";
const groups = raw.filter((result) => result?.ok && Array.isArray(result?.value?.ratings)).map((result) => result.value);
if (groups.length !== 5) throw new Error(`Expected five completed council reviews; received ${groups.length}`);
const ratingsByTicker = new Map();
for (const group of groups) {
  for (const rating of group.ratings) {
    const entries = ratingsByTicker.get(rating.ticker) ?? [];
    entries.push({ ...rating, reviewer: group.reviewer });
    ratingsByTicker.set(rating.ticker, entries);
  }
}
ratingsByTicker.set("NTAP", ntap.reviews);

const classifications = manifest.tickers.map((company) => {
  const reviews = ratingsByTicker.get(company.ticker);
  if (!reviews || reviews.length !== 5) throw new Error(`Expected five reviews for ${company.ticker}; received ${reviews?.length ?? 0}`);
  const votes = Object.fromEntries(stanceOrder.map((stance) => [stance, reviews.filter((review) => review.stance === stance).length]));
  const stance = [...stanceOrder].sort((left, right) => votes[right] - votes[left] || stanceOrder.indexOf(left) - stanceOrder.indexOf(right))[0];
  const agreeingReviews = reviews.filter((review) => review.stance === stance);
  const averageConviction = reviews.reduce((total, review) => total + convictionValue[review.conviction], 0) / reviews.length;
  const agreementCount = votes[stance];
  return {
    ticker: company.ticker,
    name: company.name,
    category: company.category,
    stance,
    conviction: convictionLabel(averageConviction),
    voteCount: agreementCount,
    reviewCount: reviews.length,
    agreement: agreementCount === 5 ? "unanimous" : agreementCount >= 4 ? "strong" : agreementCount >= 3 ? "majority" : "split",
    votes,
    rationale: agreeingReviews[0].rationale,
  };
});
const byStance = Object.fromEntries(stanceOrder.map((stance) => [stance, classifications.filter((item) => item.stance === stance).length]));
const consensus = {
  asOf,
  methodology: "Five independent structural AI-infrastructure reviews reconciled by majority vote. This is a capex-thesis exposure classification, not a price target or investment recommendation.",
  reviewers: groups.map((group) => group.reviewer),
  universeSize: classifications.length,
  byStance,
  sharedThemes: [
    "Accelerators, networking, power management, cooling, and grid interconnection are the clearest direct buildout bottlenecks.",
    "Hyperscalers are both capacity buyers and monetizers, so cash-flow discipline and utilization matter alongside demand.",
    "Power availability, transmission, cooling, and permitted sites can redirect the capex pool without reducing total compute ambition.",
    "Neocloud and converted power-site models carry asymmetric funding, utilization, counterparty, and execution exposure.",
  ],
  caveats: [
    "The reviews used durable business-model relationships and the documented universe—not current valuation, earnings estimates, or price targets.",
    "A capex-winner or capex-risk classification is not a forecast of share-price performance or personalized investment advice.",
    "Classifications should be refreshed as financing, power contracts, capacity delivery, customer concentration, and competitive conditions change.",
  ],
  classifications,
};
const dataDir = join(root, "data");
const clientDir = join(root, "client", "src", "data");
await mkdir(dataDir, { recursive: true });
await mkdir(clientDir, { recursive: true });
await writeFile(join(dataDir, `ai_capex_council_consensus_${asOf}.json`), `${JSON.stringify(consensus, null, 2)}\n`);
const ts = `/** Generated by scripts/build-ai-capex-council-consensus.mjs on ${asOf}. */\nexport const AI_CAPEX_COUNCIL = ${JSON.stringify(consensus)} as const;\nexport type AiCapexStance = (typeof AI_CAPEX_COUNCIL.classifications)[number][\"stance\"];\n`;
await writeFile(join(clientDir, "aiCapexCouncil.ts"), ts);
console.log(JSON.stringify({ universeSize: consensus.universeSize, byStance, unanimous: classifications.filter((item) => item.agreement === "unanimous").length, outputs: [join(dataDir, `ai_capex_council_consensus_${asOf}.json`), join(clientDir, "aiCapexCouncil.ts")] }, null, 2));
