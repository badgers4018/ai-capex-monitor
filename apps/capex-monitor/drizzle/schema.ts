import { int, mysqlEnum, mysqlTable, text, timestamp, varchar } from "drizzle-orm/mysql-core";

/**
 * Core user table backing auth flow.
 * Extend this file with additional tables as your product grows.
 * Columns use camelCase to match both database fields and generated types.
 */
export const users = mysqlTable("users", {
  /**
   * Surrogate primary key. Auto-incremented numeric value managed by the database.
   * Use this for relations between tables.
   */
  id: int("id").autoincrement().primaryKey(),
  /** Manus OAuth identifier (openId) returned from the OAuth callback. Unique per user. */
  openId: varchar("openId", { length: 64 }).notNull().unique(),
  name: text("name"),
  email: varchar("email", { length: 320 }),
  loginMethod: varchar("loginMethod", { length: 64 }),
  role: mysqlEnum("role", ["user", "admin"]).default("user").notNull(),
  createdAt: timestamp("createdAt").defaultNow().notNull(),
  updatedAt: timestamp("updatedAt").defaultNow().onUpdateNow().notNull(),
  lastSignedIn: timestamp("lastSignedIn").defaultNow().notNull(),
});

export type User = typeof users.$inferSelect;
export type InsertUser = typeof users.$inferInsert;

/**
 * Changelog entries generated by the weekly refresh system.
 * Each entry represents a research finding or update.
 */
export const changelogEntries = mysqlTable("changelog_entries", {
  id: int("id").autoincrement().primaryKey(),
  /** Date of the entry (e.g., "Jul 12, 2026") */
  date: varchar("date", { length: 32 }).notNull(),
  /** Category tag (e.g., "NVIDIA", "Power Grid", "CoreWeave") */
  tag: varchar("tag", { length: 64 }).notNull(),
  /** Headline text */
  headline: text("headline").notNull(),
  /** Optional detail/body text */
  detail: text("detail"),
  /** Signal direction: bullish, bearish, neutral */
  signal: mysqlEnum("signal", ["bullish", "bearish", "neutral"]).default("neutral").notNull(),
  /** Source attribution */
  source: varchar("source", { length: 256 }),
  /** Which refresh run generated this entry */
  refreshRunId: int("refreshRunId"),
  /** UTC timestamp of creation */
  createdAt: timestamp("createdAt").defaultNow().notNull(),
});

export type ChangelogEntry = typeof changelogEntries.$inferSelect;
export type InsertChangelogEntry = typeof changelogEntries.$inferInsert;

/**
 * Tracks each weekly refresh execution.
 */
export const refreshRuns = mysqlTable("refresh_runs", {
  id: int("id").autoincrement().primaryKey(),
  /** Heartbeat task UID that triggered this run */
  taskUid: varchar("taskUid", { length: 65 }),
  /** Status: running, completed, failed */
  status: mysqlEnum("status", ["running", "completed", "failed"]).default("running").notNull(),
  /** Number of topics processed */
  topicsProcessed: int("topicsProcessed").default(0),
  /** Summary from the LLM */
  summary: text("summary"),
  /** Error message if failed */
  errorMessage: text("errorMessage"),
  /** Start time */
  startedAt: timestamp("startedAt").defaultNow().notNull(),
  /** Completion time */
  completedAt: timestamp("completedAt"),
});

/**
 * Newsletter subscribers collected from the landing page and dashboard forms.
 */
export const subscribers = mysqlTable("subscribers", {
  id: int("id").autoincrement().primaryKey(),
  /** Subscriber email, unique to prevent duplicates */
  email: varchar("email", { length: 320 }).notNull().unique(),
  /** Where the subscription came from: landing or dashboard */
  source: varchar("source", { length: 32 }).default("landing").notNull(),
  /** Subscription status for future unsubscribe support */
  status: mysqlEnum("status", ["active", "unsubscribed"]).default("active").notNull(),
  createdAt: timestamp("createdAt").defaultNow().notNull(),
});

export type Subscriber = typeof subscribers.$inferSelect;
export type InsertSubscriber = typeof subscribers.$inferInsert;
